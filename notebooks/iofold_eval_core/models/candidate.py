"""
Candidate data models for iofold-eval-core.

These models represent reward function and eval candidates.
"""

from dataclasses import dataclass, field
from typing import Optional, Any, Dict, List
import json


@dataclass
class RewardCandidate:
    """
    A candidate reward function generated by the deep agent.

    Reward functions evaluate trace quality and return a score.
    """
    code: str
    iteration: int
    val_accuracy: float
    val_pearson: float
    strategy: str
    reasoning: str
    val_kappa: float = 0.0
    val_f1: float = 0.0
    created_at: Optional[str] = None

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "RewardCandidate":
        """Create RewardCandidate from a dictionary."""
        return cls(
            code=data["code"],
            iteration=data.get("iteration", 0),
            val_accuracy=float(data.get("val_accuracy", 0.0)),
            val_pearson=float(data.get("val_pearson", 0.0)),
            strategy=data.get("strategy", "unknown"),
            reasoning=data.get("reasoning", ""),
            val_kappa=float(data.get("val_kappa", 0.0)),
            val_f1=float(data.get("val_f1", 0.0)),
            created_at=data.get("created_at"),
        )

    def to_dict(self) -> Dict[str, Any]:
        """Convert RewardCandidate to dictionary."""
        return {
            "code": self.code,
            "iteration": self.iteration,
            "val_accuracy": self.val_accuracy,
            "val_pearson": self.val_pearson,
            "strategy": self.strategy,
            "reasoning": self.reasoning,
            "val_kappa": self.val_kappa,
            "val_f1": self.val_f1,
            "created_at": self.created_at,
        }


@dataclass
class EvalCandidate:
    """
    Represents an eval candidate from the database.

    Eval candidates are tested reward functions that may be activated
    for production use.
    """
    id: str
    agent_id: str
    code: str
    variation: str
    status: str  # 'candidate' | 'testing' | 'active' | 'rejected'
    agreement_rate: Optional[float]
    accuracy: Optional[float]
    cohen_kappa: Optional[float]
    f1_score: Optional[float]
    confusion_matrix: Optional[Dict[str, Any]]
    per_trace_results: Optional[List[Dict[str, Any]]]
    total_cost_usd: Optional[float]
    avg_duration_ms: Optional[float]
    created_at: str
    activated_at: Optional[str]

    @classmethod
    def from_row(cls, row: Dict[str, Any]) -> "EvalCandidate":
        """Create EvalCandidate from database row (with JSON string parsing)."""
        return cls(
            id=row["id"],
            agent_id=row["agent_id"],
            code=row["code"],
            variation=row.get("variation", ""),
            status=row.get("status", "candidate"),
            agreement_rate=row.get("agreement_rate"),
            accuracy=row.get("accuracy"),
            cohen_kappa=row.get("cohen_kappa"),
            f1_score=row.get("f1_score"),
            confusion_matrix=json.loads(row["confusion_matrix"]) if isinstance(row.get("confusion_matrix"), str) and row["confusion_matrix"] else row.get("confusion_matrix"),
            per_trace_results=json.loads(row["per_trace_results"]) if isinstance(row.get("per_trace_results"), str) and row["per_trace_results"] else row.get("per_trace_results"),
            total_cost_usd=row.get("total_cost_usd"),
            avg_duration_ms=row.get("avg_duration_ms"),
            created_at=row.get("created_at", ""),
            activated_at=row.get("activated_at"),
        )

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "EvalCandidate":
        """Create EvalCandidate from a dictionary (no JSON parsing)."""
        return cls(
            id=data["id"],
            agent_id=data["agent_id"],
            code=data["code"],
            variation=data.get("variation", ""),
            status=data.get("status", "candidate"),
            agreement_rate=data.get("agreement_rate"),
            accuracy=data.get("accuracy"),
            cohen_kappa=data.get("cohen_kappa"),
            f1_score=data.get("f1_score"),
            confusion_matrix=data.get("confusion_matrix"),
            per_trace_results=data.get("per_trace_results"),
            total_cost_usd=data.get("total_cost_usd"),
            avg_duration_ms=data.get("avg_duration_ms"),
            created_at=data.get("created_at", ""),
            activated_at=data.get("activated_at"),
        )

    def to_dict(self) -> Dict[str, Any]:
        """Convert EvalCandidate to dictionary."""
        return {
            "id": self.id,
            "agent_id": self.agent_id,
            "code": self.code,
            "variation": self.variation,
            "status": self.status,
            "agreement_rate": self.agreement_rate,
            "accuracy": self.accuracy,
            "cohen_kappa": self.cohen_kappa,
            "f1_score": self.f1_score,
            "confusion_matrix": self.confusion_matrix,
            "per_trace_results": self.per_trace_results,
            "total_cost_usd": self.total_cost_usd,
            "avg_duration_ms": self.avg_duration_ms,
            "created_at": self.created_at,
            "activated_at": self.activated_at,
        }
